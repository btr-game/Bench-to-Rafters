/** Where each pose's two-digit number starts on the jersey. */
const NUM: Record<HeroPose, [number, number]> = { lowdribble: [13, 15], drive: [15, 21], jumper: [14, 29], hip: [8, 15], dunk: [25, 28], pass: [12, 11], defense: [14, 10], rebound: [14, 14], block: [15, 21], hook: [14, 21] };

/** The position cards' poses. */
export const POS_POSE: Record<Pos, HeroPose> = { PG: 'lowdribble', SG: 'drive', SF: 'jumper', PF: 'hip', C: 'dunk' };

