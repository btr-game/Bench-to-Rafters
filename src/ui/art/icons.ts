export function archetypeIcon(name: string): string {
  const n = name.toLowerCase();
  if (/shoot|stretch|3&d/.test(n)) return 'shoot';
  if (/play|general|forward$|combo/.test(n) && !/two-way/.test(n)) return 'playmake';
  if (/slash|rim runner|lob/.test(n)) return 'finish';
  if (/scor|creator/.test(n)) return 'flame';
  if (/two-way|defen/.test(n)) return 'perimeter';
  if (/protect/.test(n)) return 'interior';
  if (/speed|athletic/.test(n)) return 'athletic';
  if (/bruis/.test(n)) return 'strength';
  if (/post/.test(n)) return 'post';
  if (/glue/.test(n)) return 'teamfirst';
  return 'iq';
}
